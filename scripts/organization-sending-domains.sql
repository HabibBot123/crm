-- Organization sending domains (Resend platform account)
-- Applied via Supabase MCP 2026-10-12. Re-run safe if already applied.

create table if not exists public.organization_sending_domains (
  id bigint generated by default as identity primary key,
  organization_id bigint not null references public.organizations (id) on delete cascade,
  domain_name text not null,
  resend_domain_id text not null,
  status text not null default 'pending',
  region text not null default 'eu-west-1',
  dns_records jsonb not null default '[]'::jsonb,
  verified_at timestamptz null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint organization_sending_domains_org_unique unique (organization_id),
  constraint organization_sending_domains_resend_unique unique (resend_domain_id),
  constraint organization_sending_domains_domain_unique unique (domain_name),
  constraint organization_sending_domains_status_check
    check (status in ('pending', 'verified', 'failed', 'temporary_failure', 'not_started')),
  constraint organization_sending_domains_region_check
    check (region in ('us-east-1', 'eu-west-1', 'sa-east-1', 'ap-northeast-1')),
  constraint organization_sending_domains_name_format
    check (domain_name ~* '^[a-z0-9]([a-z0-9-]*[a-z0-9])?(\.[a-z0-9]([a-z0-9-]*[a-z0-9])?)+$')
);

create index if not exists organization_sending_domains_org_idx
  on public.organization_sending_domains (organization_id);

comment on table public.organization_sending_domains is
  'Per-org Resend sending domain (platform account). One domain per org in v1.';

alter table public.organization_sending_domains enable row level security;

drop policy if exists organization_sending_domains_select_member on public.organization_sending_domains;
create policy organization_sending_domains_select_member
  on public.organization_sending_domains
  for select
  to authenticated
  using (public.is_org_member(organization_id));

drop policy if exists organization_sending_domains_write_settings on public.organization_sending_domains;
create policy organization_sending_domains_write_settings
  on public.organization_sending_domains
  for all
  to authenticated
  using (public.has_org_capability(organization_id, 'org.settings'))
  with check (public.has_org_capability(organization_id, 'org.settings'));

grant select, insert, update, delete on public.organization_sending_domains to authenticated;
grant usage, select on sequence public.organization_sending_domains_id_seq to authenticated;
