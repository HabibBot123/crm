-- Campaign segments (filter AST + Resend sac)
-- Applied via Supabase MCP 2026-10-13.

create table if not exists public.campaign_segments (
  id bigint generated by default as identity primary key,
  organization_id bigint not null references public.organizations (id) on delete cascade,
  name text not null,
  filter_json jsonb not null default '{"op":"and","conditions":[]}'::jsonb,
  resend_segment_id text null,
  last_synced_at timestamptz null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint campaign_segments_org_name_unique unique (organization_id, name),
  constraint campaign_segments_name_nonempty check (length(btrim(name)) > 0)
);

create index if not exists campaign_segments_org_id_idx
  on public.campaign_segments (organization_id);

alter table public.campaign_segments enable row level security;

drop policy if exists campaign_segments_select_member on public.campaign_segments;
drop policy if exists campaign_segments_select_manage on public.campaign_segments;
create policy campaign_segments_select_manage
  on public.campaign_segments
  for select
  to authenticated
  using (has_org_capability(organization_id, 'campaigns.manage'));

drop policy if exists campaign_segments_write_settings on public.campaign_segments;
drop policy if exists campaign_segments_write_manage on public.campaign_segments;
create policy campaign_segments_write_manage
  on public.campaign_segments
  for all
  to authenticated
  using (has_org_capability(organization_id, 'campaigns.manage'))
  with check (has_org_capability(organization_id, 'campaigns.manage'));
