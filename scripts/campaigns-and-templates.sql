-- Campaign email templates + campaigns (Étape 5)
-- Applied via Supabase MCP 2026-10-13.

create table if not exists public.campaign_email_templates (
  id bigint generated by default as identity primary key,
  organization_id bigint not null references public.organizations (id) on delete cascade,
  name text not null,
  subject text not null default '',
  body_json jsonb not null default '{}'::jsonb,
  body_html text not null default '',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint campaign_email_templates_org_name_unique unique (organization_id, name),
  constraint campaign_email_templates_name_nonempty check (length(btrim(name)) > 0)
);

create index if not exists campaign_email_templates_org_id_idx
  on public.campaign_email_templates (organization_id);

alter table public.campaign_email_templates enable row level security;

drop policy if exists campaign_email_templates_select_manage on public.campaign_email_templates;
create policy campaign_email_templates_select_manage
  on public.campaign_email_templates
  for select
  to authenticated
  using (has_org_capability(organization_id, 'campaigns.manage'));

drop policy if exists campaign_email_templates_write_manage on public.campaign_email_templates;
create policy campaign_email_templates_write_manage
  on public.campaign_email_templates
  for all
  to authenticated
  using (has_org_capability(organization_id, 'campaigns.manage'))
  with check (has_org_capability(organization_id, 'campaigns.manage'));

create table if not exists public.campaigns (
  id bigint generated by default as identity primary key,
  organization_id bigint not null references public.organizations (id) on delete cascade,
  name text not null,
  segment_id bigint not null references public.campaign_segments (id) on delete restrict,
  template_id bigint null references public.campaign_email_templates (id) on delete set null,
  subject text not null,
  body_html text not null default '',
  body_json jsonb not null default '{}'::jsonb,
  preview_text text null,
  from_name text not null,
  from_email text not null,
  reply_to text null,
  status text not null default 'draft'
    check (status = any (array[
      'draft'::text,
      'scheduled'::text,
      'sending'::text,
      'sent'::text,
      'canceled'::text
    ])),
  scheduled_at timestamptz null,
  sent_at timestamptz null,
  resend_broadcast_id text null,
  snapshot_html text null,
  snapshot_text text null,
  snapshot_subject text null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint campaigns_name_nonempty check (length(btrim(name)) > 0),
  constraint campaigns_subject_nonempty check (length(btrim(subject)) > 0),
  constraint campaigns_from_email_nonempty check (length(btrim(from_email)) > 0)
);

create index if not exists campaigns_org_id_idx
  on public.campaigns (organization_id);

create index if not exists campaigns_org_status_idx
  on public.campaigns (organization_id, status);

alter table public.campaigns enable row level security;

drop policy if exists campaigns_select_manage on public.campaigns;
create policy campaigns_select_manage
  on public.campaigns
  for select
  to authenticated
  using (has_org_capability(organization_id, 'campaigns.manage'));

drop policy if exists campaigns_write_manage on public.campaigns;
create policy campaigns_write_manage
  on public.campaigns
  for all
  to authenticated
  using (has_org_capability(organization_id, 'campaigns.manage'))
  with check (has_org_capability(organization_id, 'campaigns.manage'));
