where marketing_opt_in is distinct from true;

update public.campaign_contacts
set
  marketing_opt_in = true,
  opted_in_at = coalesce(opted_in_at, now()),
  opted_out_at = null,
  updated_at = now()
where marketing_opt_in is distinct from true
   or opted_out_at is not null;

create table if not exists public.campaign_topics (
  id bigint generated by default as identity primary key,
  organization_id bigint not null references public.organizations (id) on delete cascade,
  name text not null default 'Marketing',
  resend_topic_id text null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint campaign_topics_org_name_unique unique (organization_id, name)
);

alter table public.campaign_topics enable row level security;

create table if not exists public.campaign_contacts (
  id bigint generated by default as identity primary key,
  organization_id bigint not null references public.organizations (id) on delete cascade,
  email text not null,
  marketing_opt_in boolean not null default false,
  opted_in_at timestamptz null,
  opted_out_at timestamptz null,
  lead_id bigint null references public.leads (id) on delete set null,
  enrollment_id bigint null references public.enrollments (id) on delete set null,
  resend_contact_id text null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint campaign_contacts_org_email_unique unique (organization_id, email),
  constraint campaign_contacts_email_lower check (email = lower(email))
);

alter table public.campaign_contacts enable row level security;

-- Seed Marketing topic on org create
create or replace function public.organizations_seed_campaign_topic()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.campaign_topics (organization_id, name, resend_topic_id)
  values (new.id, 'Marketing', null)
  on conflict (organization_id, name) do nothing;
  return new;
end;
$$;

drop trigger if exists organizations_seed_campaign_topic_trigger on public.organizations;
create trigger organizations_seed_campaign_topic_trigger
  after insert on public.organizations
  for each row
  execute function public.organizations_seed_campaign_topic();

-- Sync contact from lead (opt-in from leads.marketing_opt_in)
create or replace function public.sync_campaign_contact_from_lead()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  v_email text := lower(btrim(new.email));
  v_now timestamptz := now();
begin
  if v_email is null or v_email = '' then
    return new;
  end if;

  insert into public.campaign_contacts (
    organization_id,
    email,
    marketing_opt_in,
    opted_in_at,
    opted_out_at,
    lead_id
  ) values (
    new.organization_id,
    v_email,
    coalesce(new.marketing_opt_in, false),
    case when coalesce(new.marketing_opt_in, false) then v_now else null end,
    null,
    new.id
  )
  on conflict (organization_id, email) do update set
    lead_id = excluded.lead_id,
    marketing_opt_in = excluded.marketing_opt_in,
    opted_in_at = case
      when excluded.marketing_opt_in then coalesce(campaign_contacts.opted_in_at, v_now)
      else campaign_contacts.opted_in_at
    end,
    opted_out_at = case
      when excluded.marketing_opt_in then null
      else v_now
    end,
    updated_at = v_now;

  return new;
end;
$$;

drop trigger if exists leads_sync_campaign_contact on public.leads;
create trigger leads_sync_campaign_contact
  after insert or update of email, marketing_opt_in, organization_id
  on public.leads
  for each row
  execute function public.sync_campaign_contact_from_lead();

-- Sync contact from enrollment (clients: auto opt-in true for now)
create or replace function public.sync_campaign_contact_from_enrollment()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  v_email text := lower(btrim(coalesce(new.buyer_email, '')));
  v_now timestamptz := now();
begin
  if v_email = '' then
    return new;
  end if;

  insert into public.campaign_contacts (
    organization_id,
    email,
    marketing_opt_in,
    opted_in_at,
    opted_out_at,
    enrollment_id
  ) values (
    new.organization_id,
    v_email,
    true,
    v_now,
    null,
    new.id
  )
  on conflict (organization_id, email) do update set
    enrollment_id = excluded.enrollment_id,
    marketing_opt_in = true,
    opted_in_at = coalesce(campaign_contacts.opted_in_at, v_now),
    opted_out_at = null,
    updated_at = v_now;

  return new;
end;
$$;

drop trigger if exists enrollments_sync_campaign_contact on public.enrollments;
create trigger enrollments_sync_campaign_contact
  after insert or update of buyer_email, organization_id
  on public.enrollments
  for each row
  execute function public.sync_campaign_contact_from_enrollment();

-- Backfill topics for existing orgs
insert into public.campaign_topics (organization_id, name, resend_topic_id)
select o.id, 'Marketing', null
from public.organizations o
where o.deleted_at is null
on conflict (organization_id, name) do nothing;

-- Backfill contacts from leads (one row per org+email)
insert into public.campaign_contacts (
  organization_id, email, marketing_opt_in, opted_in_at, lead_id
)
select organization_id, email, marketing_opt_in, opted_in_at, id
from (
  select distinct on (organization_id, lower(btrim(email)))
    organization_id,
    lower(btrim(email)) as email,
    coalesce(marketing_opt_in, false) as marketing_opt_in,
    case when coalesce(marketing_opt_in, false) then coalesce(created_at, now()) else null end as opted_in_at,
    id
  from public.leads
  where email is not null and btrim(email) <> ''
  order by organization_id, lower(btrim(email)), created_at desc nulls last
) l
on conflict (organization_id, email) do update set
  lead_id = excluded.lead_id,
  marketing_opt_in = excluded.marketing_opt_in,
  opted_in_at = case
    when excluded.marketing_opt_in then coalesce(campaign_contacts.opted_in_at, excluded.opted_in_at)
    else campaign_contacts.opted_in_at
  end,
  updated_at = now();

-- Backfill contacts from enrollments (opt-in true)
insert into public.campaign_contacts (
  organization_id, email, marketing_opt_in, opted_in_at, enrollment_id
)
select organization_id, email, true, opted_in_at, id
from (
  select distinct on (organization_id, lower(btrim(buyer_email)))
    organization_id,
    lower(btrim(buyer_email)) as email,
    coalesce(created_at, now()) as opted_in_at,
    id
  from public.enrollments
  where buyer_email is not null and btrim(buyer_email) <> ''
  order by organization_id, lower(btrim(buyer_email)), created_at desc nulls last
) e
on conflict (organization_id, email) do update set
  enrollment_id = excluded.enrollment_id,
  marketing_opt_in = true,
  opted_in_at = coalesce(campaign_contacts.opted_in_at, excluded.opted_in_at),
  opted_out_at = null,
  updated_at = now();

