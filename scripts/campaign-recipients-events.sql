-- Campaign delivery tracking (Étape 6)
-- recipients + email events + funnel stats RPC.

create table if not exists public.campaign_recipients (
  id bigint generated by default as identity primary key,
  organization_id bigint not null references public.organizations (id) on delete cascade,
  campaign_id bigint not null references public.campaigns (id) on delete cascade,
  campaign_contact_id bigint null references public.campaign_contacts (id) on delete set null,
  email text not null,
  provider_recipient_id text null,
  last_status text not null default 'queued'
    check (last_status = any (array[
      'queued'::text,
      'sent'::text,
      'delivered'::text,
      'opened'::text,
      'clicked'::text,
      'bounced'::text,
      'complained'::text,
      'delivery_delayed'::text,
      'failed'::text,
      'suppressed'::text,
      'unsubscribed'::text
    ])),
  last_status_at timestamptz not null default now(),
  sent_at timestamptz null,
  delivered_at timestamptz null,
  opened_at timestamptz null,
  clicked_at timestamptz null,
  bounced_at timestamptz null,
  complained_at timestamptz null,
  unsubscribed_at timestamptz null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint campaign_recipients_email_nonempty check (length(btrim(email)) > 0),
  constraint campaign_recipients_campaign_email_unique unique (campaign_id, email)
);

create index if not exists campaign_recipients_org_campaign_idx
  on public.campaign_recipients (organization_id, campaign_id);

create index if not exists campaign_recipients_provider_idx
  on public.campaign_recipients (provider_recipient_id)
  where provider_recipient_id is not null;

create index if not exists campaign_recipients_campaign_status_idx
  on public.campaign_recipients (campaign_id, last_status);

alter table public.campaign_recipients enable row level security;

drop policy if exists campaign_recipients_select_manage on public.campaign_recipients;
create policy campaign_recipients_select_manage
  on public.campaign_recipients
  for select
  to authenticated
  using (has_org_capability(organization_id, 'campaigns.manage'));

drop policy if exists campaign_recipients_write_manage on public.campaign_recipients;
create policy campaign_recipients_write_manage
  on public.campaign_recipients
  for all
  to authenticated
  using (has_org_capability(organization_id, 'campaigns.manage'))
  with check (has_org_capability(organization_id, 'campaigns.manage'));

create table if not exists public.campaign_email_events (
  id bigint generated by default as identity primary key,
  organization_id bigint not null references public.organizations (id) on delete cascade,
  campaign_id bigint not null references public.campaigns (id) on delete cascade,
  recipient_id bigint not null references public.campaign_recipients (id) on delete cascade,
  event_type text not null
    check (event_type = any (array[
      'queued'::text,
      'sent'::text,
      'delivered'::text,
      'opened'::text,
      'clicked'::text,
      'bounced'::text,
      'complained'::text,
      'delivery_delayed'::text,
      'failed'::text,
      'suppressed'::text,
      'unsubscribed'::text
    ])),
  occurred_at timestamptz not null,
  provider_event_id text not null,
  meta jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  constraint campaign_email_events_provider_event_unique unique (provider_event_id)
);

create index if not exists campaign_email_events_recipient_occurred_idx
  on public.campaign_email_events (recipient_id, occurred_at);

create index if not exists campaign_email_events_campaign_type_idx
  on public.campaign_email_events (campaign_id, event_type);

alter table public.campaign_email_events enable row level security;

drop policy if exists campaign_email_events_select_manage on public.campaign_email_events;
create policy campaign_email_events_select_manage
  on public.campaign_email_events
  for select
  to authenticated
  using (has_org_capability(organization_id, 'campaigns.manage'));

drop policy if exists campaign_email_events_write_manage on public.campaign_email_events;
create policy campaign_email_events_write_manage
  on public.campaign_email_events
  for all
  to authenticated
  using (has_org_capability(organization_id, 'campaigns.manage'))
  with check (has_org_capability(organization_id, 'campaigns.manage'));

-- Funnel stats from recipient first-timestamps (not exclusive last_status).
create or replace function public.campaign_delivery_stats(
  p_organization_id bigint,
  p_campaign_id bigint default null
)
returns table (
  campaign_id bigint,
  recipients bigint,
  sent bigint,
  delivered bigint,
  opened bigint,
  clicked bigint,
  bounced bigint,
  complained bigint,
  unsubscribed bigint
)
language plpgsql
stable
security invoker
set search_path = public
as $$
begin
  if not public.has_org_capability(p_organization_id, 'campaigns.manage') then
    raise exception 'forbidden';
  end if;

  return query
  select
    r.campaign_id,
    count(*)::bigint as recipients,
    count(*) filter (where r.sent_at is not null)::bigint as sent,
    count(*) filter (where r.delivered_at is not null)::bigint as delivered,
    count(*) filter (where r.opened_at is not null)::bigint as opened,
    count(*) filter (where r.clicked_at is not null)::bigint as clicked,
    count(*) filter (where r.bounced_at is not null)::bigint as bounced,
    count(*) filter (where r.complained_at is not null)::bigint as complained,
    count(*) filter (where r.unsubscribed_at is not null)::bigint as unsubscribed
  from public.campaign_recipients r
  where r.organization_id = p_organization_id
    and (p_campaign_id is null or r.campaign_id = p_campaign_id)
  group by r.campaign_id;
end;
$$;

revoke all on function public.campaign_delivery_stats(bigint, bigint) from public;
grant execute on function public.campaign_delivery_stats(bigint, bigint) to authenticated;
